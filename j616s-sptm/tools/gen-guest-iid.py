"""guest-iid.dtsi: MTP and DCP nodes of the daily J616s DT, moved onto apple,dart-apif.
usage: gen-guest-iid.py <t6040-j616s.dtb> guest-iid-res.dtsi > guest-iid.dtsi
Every device property is copied from the daily DTB; only the DART providers, status and DCP memory regions change.
Placeholders are filled from the live ADT by monitor/iommu.c; a node whose facts did not pass keeps status "mhold-*"."""
import struct, sys, libfdt
t = libfdt.Fdt(open(sys.argv[1], 'rb').read())
STR = {'compatible', 'reg-names', 'mbox-names', 'interrupt-names', 'firmware-name', 'status', 'memory-region-names'}
def props(off):
    p = t.first_property_offset(off, libfdt.QUIET_NOTFOUND)
    out = []
    while p >= 0:
        pr = t.get_property_by_offset(p)
        out.append((pr.name, bytes(pr)))
        p = t.next_property_offset(p, libfdt.QUIET_NOTFOUND)
    return out
PH = {}
def off(path): return t.path_offset(path)
for label, path in (('aic', '/interrupt-controller@502400000'), ('smc', '/smc@50c600000'), ('dart_mtp', '/iommu@514800000'),
                    ('disp0_dart', '/iommu@402300000'), ('dcp_dart', '/iommu@402340000'), ('dcp_mbox', '/mailbox@402e08000'),
                    ('mtp_mbox', '/mailbox@514608000'), ('mtp', '/mtp@514600000'), ('pmgr_dcp', '/power-management@504800000'),
                    ('mtp_dockchannel', '/fifo@514b14000')):
    PH[t.get_phandle(off(path))] = label
FIRST_PH = {'mboxes', 'apple,helper-cpu', 'apple,afe-smc', 'apple,bw-scratch', 'iommus', 'interrupt-parent'}
def fmt(name, v):
    if name in STR:
        return ', '.join('"%s"' % s.decode() for s in v[:-1].split(b'\0'))
    if not v:
        return None
    if len(v) % 4:
        return '[' + v.hex() + ']'
    c = struct.unpack('>%dI' % (len(v) // 4), v)
    if name in FIRST_PH:
        return '<&%s%s>' % (PH[c[0]], ''.join(' 0x%x' % x for x in c[1:]))
    return '<' + ' '.join('0x%x' % x for x in c) + '>'
DROP = {'phandle', 'status', 'power-domains'}
def emit(path, label, depth, extra=(), status=None, drop=()):
    o = off(path)
    name = t.get_name(o)
    tab = '\t' * depth
    print('%s%s%s {' % (tab, label + ': ' if label else '', name))
    for n, v in props(o):
        if n in DROP or n in drop:
            continue
        f = fmt(n, v)
        if n == 'hid-country-code':
            f = '<0xba5e0604>'   # live ADT kblang-calibration, as the raw loader's dt_set_ipd
        print('%s\t%s%s;' % (tab, n, ' = ' + f if f is not None else ''))
    for x in extra:
        print('%s\t%s;' % (tab, x))
    if status:
        print('%s\tstatus = "%s";' % (tab, status))
    c = t.first_subnode(o, libfdt.QUIET_NOTFOUND)
    while c >= 0:
        cn = t.get_name(c)
        yield_extra = CHILD.get(path + '/' + cn, ())
        emit_child(path + '/' + cn, depth + 1, yield_extra)
        c = t.next_subnode(c, libfdt.QUIET_NOTFOUND)
    print('%s};' % tab)
CHILD = {}
def emit_child(path, depth, extra):
    emit(path, None, depth, extra)
print('// generated by tools/gen-guest-iid.py from the daily t6040-j616s.dtb; do not edit, change the generator')
print('// iommu-addresses are left out: under apple,dart-apif the retained runs come from BOOT_IOMMU, a direct mapping would')
print('// replay them through MAP. Handoff markers are left out: the T6041 gate is for the raw loader, the monitor decides here.\n')
print('''	dart_mtp: iommu@514800000 {
		compatible = "apple,dart-apif";
		#iommu-cells = <1>;
		aurora,apif = <&apif>;
		apple,apif-dart-id = <0xba5e0601>;   // live ADT dart-mtp
		apple,apif-num-streams = <16>;       // ADT sid-count
		apple,dma-range = <0x100 0x4000 0x0 0xffff0000>;   // ADT vm-base, vm-size; monitor checks them
		status = "mhold-mtp";
	};''')
emit('/mailbox@514608000', 'mtp_mbox', 1, status='mhold-mtp')
emit('/mtp@514600000', 'mtp', 1, status='mhold-mtp')
CHILD['/fifo@514b14000/input@0/keyboard'] = ()
emit('/fifo@514b14000', 'mtp_dockchannel', 1, status='mhold-mtp')
print('''
	disp0_dart: iommu@402300000 {
		compatible = "apple,dart-apif";
		#iommu-cells = <1>;
		aurora,apif = <&apif>;
		apple,apif-dart-id = <0xba5e0602>;   // live ADT dart-disp0
		apple,apif-num-streams = <32>;
		apple,apif-retained-sids = <0 16>;
		apple,dma-range = <0x100 0x0 0x10 0x0>;
		status = "mhold-dcp";
	};
	dcp_dart: iommu@402340000 {
		compatible = "apple,dart-apif";
		#iommu-cells = <1>;
		aurora,apif = <&apif>;
		apple,apif-dart-id = <0xba5e0603>;   // live ADT dart-dcp
		apple,apif-num-streams = <32>;
		apple,apif-retained-sids = <23>;
		apple,dma-range = <0x100 0x0 0x10 0x0>;
		status = "mhold-dcp";
	};''')
emit('/power-management@504800000', 'pmgr_dcp', 1)
emit('/mailbox@402e08000', 'dcp_mbox', 1, status='mhold-dcp')
regions = ('dcp_heap', 'dcp_disp', 'dcp_pio', 'dcp_fb', 'dcp_disp2', 'dcp_text', 'dcp_data')
names = '"dcp-map-heap", "dcp-map-disp", "dcp-map-piodma", "framebuffer", "dcp-map-disp2", "dcp-map-text", "dcp-map-data"'
with open(sys.argv[2], 'w') as res:
    res.write('// generated with guest-iid.dtsi: a second root block, dtc merges it with /reserved-memory\n/ {\n\treserved-memory {\n')
    for i, r in enumerate(regions):
        ph = 0xba5e0700 + i * 4
        res.write('\t\t%s: %s@%x { reg = <0x%x 0x%x 0x%x 0x%x>; no-map; status = "mhold-dcp"; };\n' % (r, r.replace('_', '-'), i, ph, ph + 1, ph + 2, ph + 3))
    res.write('\t};\n};\n')
ref = lambda *n: '<' + ' '.join('&' + x for x in n) + '>'
CHILD['/dcp@402e00000/piodma'] = ('memory-region = <&dcp_pio>', 'memory-region-names = "dcp-map-piodma"')
emit('/dcp@402e00000', 'dcp', 1, extra=('memory-region = ' + ref(*regions), 'memory-region-names = ' + names), status='mhold-dcp')
emit('/display-subsystem', 'display_subsystem', 1, extra=('memory-region = <&dcp_disp &dcp_fb &dcp_disp2>',
     'memory-region-names = "dcp-map-disp", "framebuffer", "dcp-map-disp2"'), status='mhold-dcp')
