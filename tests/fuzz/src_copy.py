"""Copy the host-buildable device tree code out of src/kboot.c and src/payload.c for
tests/fuzz/dt_fuzz.c.

    src_copy.py <out.c>

payload.c's load_fdt() (how a payload's tree is accepted), kboot.c's SMBIOS node code
(dt_set_smbios(), dt_set_smbios_firmware() and their helpers, as tests/run-smbios.sh copies it)
and dt_disable_missing_devs() (as tests/run-usb-pruning.py copies it) are copied unchanged, with
the few things they take from the rest of aura stubbed.
"""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]

PRELUDE = r'''/* Generated by tests/fuzz/src_copy.py from src/kboot.c and src/payload.c; do not edit */
#include <assert.h>
#include <string.h>
#include "adt.h"
#include "devicetree.h"
#include "types.h"
#include "utils.h"
#include "libfdt/libfdt.h"
#include "payload_profile.h"

#define bail(...)                                                                                  \
    do {                                                                                           \
        printf(__VA_ARGS__);                                                                       \
        return -1;                                                                                 \
    } while (0)

#define bail_cleanup(...)                                                                          \
    do {                                                                                           \
        printf(__VA_ARGS__);                                                                       \
        ret = -1;                                                                                  \
        goto err;                                                                                  \
    } while (0)

static void *dt;

/* What the copied code takes from firmware.c, main.c, pmgr.c and rust/src/usb4.rs */
struct fw_version_info {
    const char *string;
    const char *iboot;
};
struct fw_version_info system_firmware = {"27.0", "mBoot-20457.1.29"};
struct fw_version_info os_firmware = {"26.6.2", "mBoot-18000.161.10"};
const char *const aura_version = "1.0.0b1-fuzz";
int rust_platform_uuid(u8 *out)
{
    for (int i = 0; i < 16; i++)
        out[i] = 0x11 * i;
    return 0;
}
u64 pmgr_die_stride(void)
{
    return 0x2000000000;
}

/* What load_fdt() takes from firmware.c and the rest of payload.c */
enum fw_version { V_OTHER, V26_6_2 };
bool fuzz_os_26_6_2;
static enum fw_version firmware_os_components(void)
{
    return fuzz_os_26_6_2 ? V26_6_2 : V_OTHER;
}
static char expect_compatible[256] = "apple,j000";
static void *fdt;
static int fdt_rank;
static void payload_scan_stopped(void)
{
}
'''

EPILOGUE = r'''
void *fuzz_load_fdt(void *p, size_t size, void **selected)
{
    fdt = NULL;
    fdt_rank = 0;
    void *next = load_fdt(p, size);
    *selected = fdt;
    return next;
}

int fuzz_set_smbios(void *d)
{
    dt = d;
    return dt_set_smbios() || dt_set_smbios_firmware();
}

int fuzz_disable_missing_devs(void *d, const char *adt_prefix, const char *dt_prefix, int max_devs,
                              int regnum)
{
    dt = d;
    return dt_disable_missing_devs(adt_prefix, dt_prefix, max_devs, regnum);
}
'''


def between(src, start, end_marker, what):
    try:
        a = src.index(start)
        b = src.index(end_marker, a)
    except ValueError:
        raise SystemExit("src_copy.py: %s not found in src/kboot.c; update the copy" % what)
    return src[a:b]


def main():
    if len(sys.argv) != 2:
        raise SystemExit(__doc__)
    src = (ROOT / "src/kboot.c").read_text()
    payload = (ROOT / "src/payload.c").read_text()
    try:
        a = payload.index("static void *load_fdt(")
        load_fdt = payload[a:payload.index("\n}\n", a)] + "\n}\n\n"
    except ValueError:
        raise SystemExit("src_copy.py: load_fdt() not found in src/payload.c; update the copy")

    # The SMBIOS block, from its comment to the end of dt_set_smbios_firmware()
    smbios = between(src, "/*\n * SMBIOS values for U-Boot", "\nstatic int dt_set_smbios_firmware(",
                     "the SMBIOS block")
    fw = between(src, "\nstatic int dt_set_smbios_firmware(", "\n}\n", "dt_set_smbios_firmware()")
    missing = between(src, "static int dt_disable_missing_devs(", "\n__attribute__",
                      "dt_disable_missing_devs()")
    Path(sys.argv[1]).write_text(PRELUDE + load_fdt + smbios + fw + "\n}\n\n" + missing + EPILOGUE)


if __name__ == "__main__":
    main()
